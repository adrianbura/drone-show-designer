import { authoredProductionProject, validateAuthored } from "@/lib/acceptance/__tests__/support/productionFixtures";
import { previewTextFormation } from "@/lib/studio/textFormationPreview";
import { buildTextCandidateProject } from "@/lib/studio/textFormationApplyCommand";
import { analyzeGeometryProposalConsequences, evaluateGeometryApplyReadiness, evaluateGeometryTrajectoryConsequence } from "@/lib/show/diagnostics";
import { defaultTextRecipe, textFormationIdFor } from "@/lib/studio/textRebuild";
const p = authoredProductionProject(60);
const base = validateAuthored(p, 8);
console.log("baseline", base.exportReadiness.status, base.exportReadiness.blockers);
const recipe = { ...defaultTextRecipe(60, "GO", 60), widthMeters: 130, heightMeters: 60 };
const pv = previewTextFormation(p, { clipId: "c-prod-wide", recipe });
if (!pv.ok) throw new Error(JSON.stringify(pv));
const rep = p.formations.find(f=>f.id===pv.replacedFormationId)!;
const pre = analyzeGeometryProposalConsequences({ before: rep.points, after: pv.points.map(q=>[q[0],q[1],q[2]] as [number,number,number]), area: p.area, limits: p.limits });
const cand = buildTextCandidateProject({ project: p, preview: pv, formationId: textFormationIdFor("c-prod-wide", pv.geometry.recipeHash) });
const traj = evaluateGeometryTrajectoryConsequence(p, cand.project, { sampleRate: 8, assignmentStrategy: "optimalDistance" as never });
const r = evaluateGeometryApplyReadiness({ staticPreflight: pre, trajectory: traj, importedPromotionAcknowledged: false });
console.log("static", { pass: pre.staticEnvelopePass, sep: pre.introducesPairSeparationViolation, alt: pre.introducesAltitudeViolation, area: pre.introducesAreaViolation, note: pre.note });
console.log("after full show", traj.after.exportReadiness, traj.after.status);
console.log("readiness", r.status, r.canApply, r.blockers, r.warnings);
const issues = (traj.after as any);
console.log(Object.keys(issues));
const full = (await import("@/lib/show/fullshow")).analyzeFullShow(cand.project, { sampleRate: 8, assignmentStrategy: "optimalDistance" as never }).report;
console.log(JSON.stringify(full.exportReadiness, null, 1));
console.log(full.issues?.slice(0,8).map((i:any)=>[i.severity,i.code??i.kind,i.message??i.note]));
